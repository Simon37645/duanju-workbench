//! 内置风格预设。短剧常用画风的起步模板，用户可以在此基础上改写。

use crate::models::StylePreset;

fn p(
    id: &str,
    name: &str,
    category: &str,
    prompt: &str,
    negative: &str,
    palette: &[&str],
    lighting: &str,
    lens: &str,
    film: &str,
    motion: &str,
) -> StylePreset {
    StylePreset {
        id: id.into(),
        name: name.into(),
        category: category.into(),
        prompt: prompt.into(),
        negative: negative.into(),
        palette: palette.iter().map(|s| s.to_string()).collect(),
        lighting: lighting.into(),
        lens: lens.into(),
        film_stock: film.into(),
        motion_style: motion.into(),
    }
}

